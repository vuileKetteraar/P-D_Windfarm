To run the models of the transposed and rotated-twisted line the m-files linetran.m and linetw.m, 
respectively, must be executed. This m-files will launch the corresponding models. In the file data.txt 
the input data for this model must be specified. The format is specified in the m-files.

The results of the calculations performed by the m-files mentioned above are saved in the 
files: outputtransp.txt and outputwist.txt.    